"""
Flock schemas — request validation and response contracts for the Flock resource.
"""

from pydantic import BaseModel, Field
from typing import Optional, List
from datetime import datetime, date


# ── Request schemas ────────────────────────────────────────────────────────────

class FlockCreate(BaseModel):
    """Body for POST /flocks — create a new flock.
    Notice `flock_code` is missing here as it's auto-generated by the backend.
    """
    house_id: int = Field(..., description="ID of the house this flock belongs to")
    breed: Optional[str] = Field(None, max_length=100, description="Breed or type of birds")
    initial_quantity: int = Field(..., gt=0, description="Starting number of birds")
    arrival_date: date = Field(..., description="Date the flock arrived")
    status: Optional[str] = Field("Active", max_length=100, description="Current status of the flock")


class FlockUpdate(BaseModel):
    """Body for PUT /flocks/{id} — all fields optional for partial updates."""
    house_id: Optional[int] = None
    breed: Optional[str] = Field(None, max_length=100)
    initial_quantity: Optional[int] = Field(None, gt=0)
    arrival_date: Optional[date] = None
    status: Optional[str] = Field(None, max_length=100)


# ── Response schemas ───────────────────────────────────────────────────────────

class FlockResponse(BaseModel):
    """Single flock response."""
    id: int
    flock_code: str
    house_id: int
    breed: Optional[str] = None
    initial_quantity: int
    current_quantity: int
    arrival_date: date
    status: Optional[str] = None
    created_by: Optional[int] = None
    created_at: Optional[datetime] = None
    updated_at: Optional[datetime] = None

    model_config = {"from_attributes": True}


class FlockListResponse(BaseModel):
    """Paginated list of flocks."""
    items: List[FlockResponse]
    total: int
    page: int
    limit: int
    pages: int
